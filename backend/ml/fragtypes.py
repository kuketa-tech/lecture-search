LABELS = {k: v["label"] for k, v in TYPES.items()} | {"explanation": "Объяснение"}


@lru_cache(maxsize=4)
def _proto_vectors(model_name: str) -> dict[str, np.ndarray]:
    from . import models
    emb = models.embedder(model_name)
    return {k: emb.passages(v["protos"]) for k, v in TYPES.items()}


def classify(vecs: np.ndarray, texts: list[str], model_name: str) -> list[str]:
    if not len(texts):
        return []
    protos = _proto_vectors(model_name)
    names = list(TYPES)
    scores = np.zeros((len(texts), len(names)), dtype=np.float32)
    for j, name in enumerate(names):
        sim = (vecs @ protos[name].T).max(axis=1)
        # z-оценка внутри лекции: «насколько эта фраза похожа на эталон сильнее, чем обычная фраза этой лекции»
        z = (sim - sim.mean()) / (sim.std() + 1e-6)
        rx = re.compile(TYPES[name]["regex"], re.IGNORECASE)
        lex = np.array([1.0 if rx.search(t) else 0.0 for t in texts], dtype=np.float32)
        scores[:, j] = z + 1.5 * lex
    best = scores.argmax(axis=1)
    return [names[b] if scores[i, b] >= 2.2 else "explanation" for i, b in enumerate(best)]


def chunk_tags(sent_types: list[str], s_from: int, s_to: int) -> list[str]:
    seen = []
    for t in sent_types[s_from:s_to + 1]:
        if t != "explanation" and t not in seen:
            seen.append(t)
    return seen
